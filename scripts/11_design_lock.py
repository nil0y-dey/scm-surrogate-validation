"""
11_design_lock.py
------------------
DESIGN LOCK. Checks that every pre-data check has passed, then writes
    configs/design_lock.json   (every frozen value + a fingerprint of the design files)
    docs/DESIGN_LOCK.md        (the same, readable, with the data budget)
You then save both to git and put a tag called `design-lock` on that save. From that
moment the design files must not change; anything that does is reported as a deviation.

It refuses to write the lock if a required report is missing or contains a FAIL.

Usage:  python scripts/11_design_lock.py [--sec-per-run 22.5] [--workers 2]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys

from scmval import design, paths, policies

R = paths.REPORT_DIR


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()[:16]


def statuses(path):
    d = json.load(open(path))
    items = d if isinstance(d, list) else d.get("checks", [])
    return [(c.get("status"), c.get("message") or c.get("check")) for c in items]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sec-per-run", type=float, default=design.SEC_PER_RUN_ESTIMATE)
    ap.add_argument("--workers", type=int, default=2)
    a = ap.parse_args()

    required = {"gate1_report.json": "Gate 1 integrity", "gate3_report.json": "Gate 3 policy viability / warm-up",
                "gate4_report.json": "Gate 4 severity mapping", "gate56_report.json": "Gates 5/6 training signal and policy power",
                "learnability_B.json": "Surrogate learnability", "pipeline_dryruns.json": "Pipeline dry runs"}
    bad, warns, ok = [], [], []
    for f, name in required.items():
        if not (R / f).exists():
            bad.append(f"{name}: report {f} is missing"); continue
        st = statuses(R / f)
        fails = [m for s, m in st if s == "FAIL"]
        if fails: bad += [f"{name}: {m}" for m in fails]
        else: ok.append(name)
        for s_, m in st:
            if s_ == "WARN":
                if "sigma<=0.2" in str(m):
                    m = f"{m}  [SUPERSEDED: severity was re-indexed to overload nu; Gates 5/6 confirm the new Mild band carries signal]"
                warns.append(f"{name}: {m}")
    print("Checks that passed:", ", ".join(ok) or "none")
    for w in warns: print("  [WARN carried into the lock]", w)
    if bad:
        print("\nCANNOT LOCK. Fix these first:"); [print("  -", b) for b in bad]; sys.exit(1)

    plan = design.run_plan(a.sec_per_run, a.workers)
    lock = {
        "locked_checks": ok, "warnings_carried": warns,
        "fingerprint": {"design.py": sha(paths.REPO_ROOT / "src/scmval/design.py"),
                        "policies.py": sha(paths.REPO_ROOT / "src/scmval/policies.py"),
                        "metrics.py": sha(paths.REPO_ROOT / "src/scmval/metrics.py"),
                        "analysis.py": sha(paths.REPO_ROOT / "src/scmval/analysis.py")},
        "design": {"T0": design.T0, "run_length": design.RUN_LENGTH, "durations": design.DURATIONS,
                   "nu_bands": design.NU_BANDS, "train_band": design.TRAIN_BAND,
                   "train_durations": design.TRAIN_DURATIONS, "delta_fill": design.DELTA_FILL,
                   "delta_unmet_days": design.delta_unmet_days(), "min_decidable_frac_eval": design.MIN_DECIDABLE_FRAC_EVAL,
                   "sensitivity_train_nu_max": design.SENSITIVITY_TRAIN_NU_MAX, "calm_only_ablation": design.ABLATION_CALM_ONLY,
                   "seed_ranges": design.SEED_RANGES, "bh_q": 0.10},
        "policies": [list(p) for p in policies.viable_grid()],
        "data_plan": {"test_nus": design.TEST_NUS, "test_durations": design.TEST_DURATIONS,
                      "n_train": design.N_TRAIN, "n_calibration": design.N_CALIBRATION, "n_calm": design.N_CALM,
                      "n_wide": design.N_WIDE, "test_seeds_first": design.TEST_SEEDS_FIRST,
                      "test_seeds_max": design.TEST_SEEDS_MAX, "placebo_cells": design.PLACEBO_CELLS,
                      "placebo_seeds": design.PLACEBO_SEEDS},
        "budget": {"sec_per_run": a.sec_per_run, "workers": a.workers, "blocks": plan},
    }
    (paths.REPO_ROOT / "configs").mkdir(exist_ok=True)
    json.dump(lock, open(paths.REPO_ROOT / "configs" / "design_lock.json", "w"), indent=2, default=list)

    L = ["# Design lock (Simulator B)", "",
         "Generated by `scripts/11_design_lock.py`. Do not edit by hand. After the git tag `design-lock`, "
         "any change to `design.py`, `policies.py`, `metrics.py` or `analysis.py` is a deviation and must be reported.", "",
         "## Checks passed", *[f"- {n}" for n in ok], "", "## Warnings carried into the lock",
         *([f"- {w}" for w in warns] or ["- none"]), "", "## Frozen design",
         f"- Disruption starts day {design.T0}; run length L = {design.RUN_LENGTH} days; durations {list(design.DURATIONS.values())}",
         f"- Severity = overload nu; bands {design.NU_BANDS}",
         f"- Training: nu in {design.TRAIN_NU_RANGE}, D in {list(design.TRAIN_DURATIONS)}; calm-only ablation and wider band (nu <= {design.SENSITIVITY_TRAIN_NU_MAX}) as sensitivity arms",
         f"- Practical margin delta = {design.DELTA_FILL*100:.1f} pp of fill rate = {design.delta_unmet_days():.1f} days of unmet demand; BH q = 0.10",
         f"- Test cells with fewer than {design.MIN_DECIDABLE_FRAC_EVAL:.0%} decidable pairs are reported but kept out of the headline flip tables",
         f"- {len(policies.viable_grid())} policies (safety-stock scale, pipeline multiplier): {policies.viable_grid()}",
         f"- Seed ranges (never reused across roles): {design.SEED_RANGES}", "",
         f"## Data budget (at {a.sec_per_run:.1f} s per run, {a.workers} parallel workers)",
         "| Block | Runs | CPU hours | Wall hours |", "|---|---:|---:|---:|"]
    L += [f"| {k} | {v['runs']} | {v['cpu_hours']} | {v['wall_hours']} |" for k, v in plan.items()]
    L += ["", "Tier 1 is essential. Tier 2 (sensitivity arms and the placebo repeat) strengthens the claims. "
          "Tier 3 is the maximum if every test cell is deepened from 15 to 30 seeds; in practice only near-margin cells are."]
    (paths.REPO_ROOT / "docs" / "DESIGN_LOCK.md").write_text("\n".join(L) + "\n")
    print("\nBudget:"); [print(f"  {k:24s} {v['runs']:6d} runs  {v['cpu_hours']:6.1f} CPU h  {v['wall_hours']:6.1f} wall h") for k, v in plan.items()]
    print("\nWrote configs/design_lock.json and docs/DESIGN_LOCK.md")
    print("DESIGN LOCK FILES WRITTEN. Now save them to git (Part 4) and add the tag (Part 5).")


if __name__ == "__main__":
    main()
