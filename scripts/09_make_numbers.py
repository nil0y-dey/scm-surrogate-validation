"""
09_make_numbers.py
-------------------
Writes docs/manuscript/numbers.tex: one LaTeX macro per number quoted in the
manuscript, read straight from results/reports/. The manuscript never contains
a typed-in result, so a re-run of a gate cannot leave the paper out of date.

Usage:  python scripts/09_make_numbers.py
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from scmval import design, paths

OUT = paths.REPO_ROOT / "docs" / "manuscript" / "numbers.tex"
R = paths.REPORT_DIR
macros: dict[str, str] = {}


def put(name: str, value, fmt: str = "{}") -> None:
    macros[name] = fmt.format(value)


def main() -> None:
    g1 = json.load(open(R / "gate1_report.json"))
    put("GateOnePass", sum(c["status"] == "PASS" for c in g1), "{:d}")
    put("GateOneFail", sum(c["status"] == "FAIL" for c in g1), "{:d}")
    g3 = json.load(open(R / "gate3_report.json"))
    put("PolicyTotal", g3["n_policies"], "{:d}")
    put("PolicyViable", g3["n_viable"], "{:d}")
    put("PolicyDropped", g3["n_policies"] - g3["n_viable"], "{:d}")
    put("SlowestSettleDay", g3["max_settle_day_viable"], "{:d}")
    put("ViableMinCalmFill", g3["settings"]["viable_min_calm_fill"], "{:.2f}")
    g4 = json.load(open(R / "gate4_report.json"))
    put("FluidK", g4["fluid_model"]["k"], "{:.2f}")
    put("FluidRsq", g4["fluid_model"]["r2"], "{:.2f}")
    put("FluidN", g4["fluid_model"]["n"], "{:d}")
    cells = pd.read_csv(R / "gate56_cells.csv")
    tr = cells[(cells.nu <= 0.15) & cells.D.isin(design.TRAIN_DURATIONS)]
    put("MildUnmetLo", tr.mean_unmet.min(), "{:.1f}")
    put("MildUnmetHi", tr.mean_unmet.max(), "{:.1f}")
    put("MildLossShareLo", 100 * tr.frac_runs_with_loss.min(), "{:.0f}")
    live = cells[cells.mean_unmet > design.delta_unmet_days()]
    put("LiveCells", len(live), "{:d}")
    put("DecidableMedian", live.decidable_frac.median(), "{:.2f}")
    put("RandomRegretAboveDelta", int((live.random_advice_regret > design.delta_unmet_days()).sum()), "{:d}")
    put("MddFiveSeeds", live.mdd_at_seeds.median(), "{:.1f}")
    put("MddThirtySeeds", live.mdd_at_30.median(), "{:.1f}")
    put("PilotSeeds", int(cells.n_seeds.max()), "{:d}")
    put("PairsPerCell", int(cells.n_pairs.max()), "{:d}")
    put("DeltaFill", 100 * design.DELTA_FILL, "{:.1f}")
    put("DeltaUnmet", design.delta_unmet_days(), "{:.1f}")
    put("RunLength", design.RUN_LENGTH, "{:d}")
    put("DisruptStart", design.T0, "{:d}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w") as f:
        f.write("% AUTO-GENERATED by scripts/09_make_numbers.py. Do not edit.\n")
        for k, v in macros.items():
            f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    print(f"wrote {OUT} ({len(macros)} numbers)")


if __name__ == "__main__":
    main()
